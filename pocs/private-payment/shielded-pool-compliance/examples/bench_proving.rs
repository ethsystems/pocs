fn build_withdraw_blocked_witness() -> BlockedWithdrawWitness {
    let world = new_world();
    let alice_sk = SpendingKey::random();
    let alice = alice_sk.derive_owner_pubkey();

    let spent_note = Note::new(world.token, 2_500, alice);
    let spent_index = world
        .commitments
        .insert(spent_note.commitment().expect("canonical"))
        .expect("insert");
    let commitment_root = world.commitments.root().expect("nonempty");

    let amount = 2_500u64;
    let recipient = Address::from([0x44; 20]);
    let nullifier = spent_note.nullifier(&alice_sk).expect("canonical");

    let public = ungated_withdraw::Fields {
        nullifier,
        token: Bytes32::from(Fr::from(world.token)),
        amount: Bytes32::from(Fr::from(amount)),
        recipient: Bytes32::from(Fr::from(recipient)),
        commitment_root,
    };
    require_canonical(&public.ordered()).expect("canonical public inputs");

    BlockedWithdrawWitness {
        public,
        spending_key: alice_sk,
        note_salt: spent_note.salt,
        note_proof: world.commitments.get_proof(spent_index).expect("proof"),
    }
}

fn error_chain(e: &dyn std::error::Error) -> String {
    let mut out = e.to_string();
    let mut source = e.source();
    while let Some(s) = source {
        out.push_str(": ");
        out.push_str(&s.to_string());
        source = s.source();
    }
    out
}

fn main() -> ExitCode {
    let home = match std::env::var("HOME") {
        Ok(h) => PathBuf::from(h),
        Err(_) => {
            eprintln!("HOME is not set");
            return ExitCode::FAILURE;
        }
    };
    let bb_path = home.join(".bb/bb");
    let nargo_path = home.join(".nargo/bin/nargo");
    let project_root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));

    let prover = match BbProver::new(&bb_path, nargo_path, project_root) {
        Ok(p) => p,
        Err(e) => {
            eprintln!("failed to start the bb backend: {e}");
            return ExitCode::FAILURE;
        }
    };

    // Transfer first: the largest circuit (188,052 gates), so it sets the PoC's
    // worst-case proving time.
    let cases: [(&str, ProofRequest); 4] = [
        (
            "transfer",
            ProofRequest::Transfer(Box::new(build_transfer_witness())),
        ),
        (
            "deposit",
            ProofRequest::Deposit(Box::new(build_deposit_witness())),
        ),
        (
            "withdraw",
            ProofRequest::Withdraw(Box::new(build_withdraw_witness())),
        ),
        (
            "withdraw_ungated",
            ProofRequest::WithdrawBlocked(Box::new(build_withdraw_blocked_witness())),
        ),
    ];

    println!(
        "{:<18} {:>12} {:>12} {:>12} {:>8}",
        "circuit", "prove_ms", "verify_ms", "proof_bytes", "ok"
    );
    let mut all_ok = true;
    for (name, request) in &cases {
        let circuit = request.circuit();

        let start = Instant::now();
        let proof = match prover.prove(request) {
            Ok(p) => p,
            Err(e) => {
                println!("{name:<18} prove FAILED: {}", error_chain(&e));
                all_ok = false;
                continue;
            }
        };
        let prove_ms = start.elapsed().as_secs_f64() * 1000.0;

        let start = Instant::now();
        let verified = match prover.verify(circuit, &proof) {
            Ok(v) => v,
            Err(e) => {
                println!("{name:<18} verify FAILED: {}", error_chain(&e));
                all_ok = false;
                continue;
            }
        };
        let verify_ms = start.elapsed().as_secs_f64() * 1000.0;

        if !verified {
            all_ok = false;
        }
        println!(
            "{name:<18} {prove_ms:>12.1} {verify_ms:>12.1} {:>12} {verified:>8}",
            proof.proof.len(),
        );
    }

    if all_ok {
        ExitCode::SUCCESS
    } else {
        ExitCode::FAILURE
    }
}
