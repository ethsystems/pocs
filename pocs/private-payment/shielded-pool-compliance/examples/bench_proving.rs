//! Proves one instance of each circuit through the real `BbProver` and reports
//! wall-clock proving/verification time and proof size. Witnesses are built directly
//! from the domain layer (`Note`, `ComplianceNote`, `tx_facts`, `VelocityNullifier`,
//! `AttestationLeaf`), mirroring exactly what `wallet::core::Wallet::build_*` computes
//! internally, but without the `Wallet`'s own async `ChainReader`/`Clock`/
//! `AttestationSource` bookkeeping: that plumbing is not what this benchmark measures.
//!
//! Every witness is its subject's first-ever compliance note (`seq == 0`), the base
//! case `ComplianceWitness` needs no predecessor proof for, so no chained prior
//! transaction has to be built and proved first just to prove the one being measured.
//!
//! Transfer is reported first: at 188,052 gates it is the largest circuit and sets the
//! PoC's worst-case proving time, which the README needs. Run with
//! `cargo run --release --example bench_proving`; a debug build is impractically slow.

