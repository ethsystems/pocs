type CommitmentTree = RotorMerkleTree<32>;
type AttestationTree = RotorMerkleTree<20>;

/// Fresh, self-contained chain-mirror state for one witness. Each circuit gets its own
/// `World` rather than sharing one across circuits, so building one witness can never
/// perturb another's Merkle roots.
struct World {
    _commitments_dir: TempDir,
    _attestations_dir: TempDir,
    commitments: CommitmentTree,
    attestations: AttestationTree,
    revocations: RevocationTree,
    attester: Address,
    token: Address,
    epoch: Epoch,
    policy_source_hash: Bytes32,
    tag: Bytes32,
}

fn new_world() -> World {
    let commitments_dir = tempfile::tempdir().expect("tempdir");
    let attestations_dir = tempfile::tempdir().expect("tempdir");
    let commitments = CommitmentTree::open(commitments_dir.path()).expect("open tree");
    let attestations = AttestationTree::open(attestations_dir.path()).expect("open tree");
    let mut revocations = RevocationTree::new();
    let attester = Address::from([0xaa; 20]);
    revocations.add_attester(attester).expect("tree has room");

    // Every gated circuit asserts `STATE_TAG`/`POLICY_SOURCE_HASH` against a live
    // Poseidon1 image of `circuits/lib/src/policy.nr` (`policy_tag::POLICY_SOURCE_HASH`,
    // generated by `cargo run --bin policy-tag`), not an arbitrary value: a witness
    // with a made-up `policy_source_hash` fails "policy_source_hash mismatch" at
    // proving time even though it is otherwise well-formed.
    let policy_nr =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("circuits/lib/src/policy.nr");
    let source_hash_fr =
        policy_source_hash(&policy_nr).expect("read circuits/lib/src/policy.nr");
    let policy_source_hash = Bytes32::from(source_hash_fr);
    let tag = Bytes32::from(state_tag::<ReferencePolicy>(source_hash_fr));

    World {
        _commitments_dir: commitments_dir,
        _attestations_dir: attestations_dir,
        commitments,
        attestations,
        revocations,
        attester,
        token: Address::from([0x11; 20]),
        epoch: Epoch(100),
        policy_source_hash,
        tag,
    }
}

fn insert_attestation_leaf(
    attestations: &AttestationTree,
    owner: OwnerPubkey,
    attester: Address,
    generation: Generation,
    issued_at: u64,
    expires_at: u64,
) -> LeafIndex {
    let leaf = AttestationLeaf {
        owner_pubkey: owner,
        attester,
        generation,
        issued_at,
        expires_at,
    }
    .hash()
    .expect("canonical owner pubkey");
    attestations
        .insert(leaf)
        .expect("attestation tree has room")
}

fn attestation_witness(
    world: &World,
    leaf_index: LeafIndex,
    generation: Generation,
    issued_at: u64,
    expires_at: u64,
) -> AttestationWitness {
    AttestationWitness {
        attester: world.attester,
        generation,
        issued_at,
        expires_at,
        attestation_proof: world.attestations.get_proof(leaf_index).expect("proof"),
        revoked_at: world
            .revocations
            .revoked_at_epoch_of(world.attester)
            .expect("attester registered"),
        revocation_proof: world
            .revocations
            .proof(world.attester)
            .expect("attester registered"),
    }
}

/// `wallet::core::Wallet::compliance_witness`'s base-case fallback (`current_note ==
/// None`) sets `epoch_in: Epoch(0)`, but the compliance gadget's `epoch_in == epoch`
/// check (`circuits/lib/src/compliance.nr:44`) is unconditional, so a first-ever
/// transaction at any epoch other than 0 fails to prove against the real circuit with
/// that value. `wallet::core` is out of this track's scope (`src/adapters/*` and
/// `examples/bench_proving.rs` only), so the base case here sets `epoch_in` to the
/// transaction's own epoch instead of copying that fallback; see the report for the
/// bug this surfaced upstream.
fn base_compliance_witness(epoch: Epoch, salt_out: Bytes32) -> ComplianceWitness {
    ComplianceWitness {
        seq: Seq(0),
        epoch_in: epoch,
        prev: ReferencePolicy::zero(),
        flags_in: 0,
        cp_in: [Bytes32::from(*shielded_pool_compliance::NO_COUNTERPARTY); 2],
        amt_in: [0, 0],
        exit_in: Bytes32::from(*shielded_pool_compliance::NO_EXIT),
        salt_in: Bytes32::from([0u8; 32]),
        salt_out,
        cn_proof: MerklePath::new(vec![]),
    }
}

fn build_deposit_witness() -> DepositWitness {
    let world = new_world();
    let alice_sk = SpendingKey::random();
    let alice = alice_sk.derive_owner_pubkey();
    let (generation, issued_at, expires_at) = (Generation(1), 0u64, u64::MAX);
    let leaf = insert_attestation_leaf(
        &world.attestations,
        alice,
        world.attester,
        generation,
        issued_at,
        expires_at,
    );
    let attestation_root = world.attestations.root().expect("nonempty");

    let epoch = world.epoch;
    let seq = Seq(0);
    let amount = 1_000u64;

    let tx =
        tx_facts::deposit(epoch, seq, world.token, alice, amount).expect("canonical");
    let prev_state = ReferencePolicy::zero();
    let next_state = ReferencePolicy::advance(prev_state, &tx).expect("no overflow");
    let flags =
        ReferencePolicy::evaluate(&tx, prev_state, next_state).expect("never blocks");

    let output_note = Note::new(world.token, amount, alice);
    let commitment = output_note.commitment().expect("canonical");
    let velocity_nullifier = VelocityNullifier::derive(&alice_sk, epoch, seq).0;
    // `circuits/deposit/src/main.nr` calls `compliance::run(.., tx, amount, 0)`: the
    // deposited amount is the compliance gadget's `amount_out_0`, not 0.
    let facts = Facts {
        counterparty: [
            Bytes32::from(tx.counterparty[0]),
            Bytes32::from(tx.counterparty[1]),
        ],
        amount_out: [amount, 0],
        exit: Bytes32::from(tx.exit),
    };
    let new_salt = random_salt();
    let new_note = ComplianceNote::<ReferencePolicy> {
        owner_pubkey: alice,
        epoch,
        // The compliance gadget embeds `inp.seq + 1` (not `inp.seq`) as the
        // seq field inside `compliance_commitment_out`'s state hash
        // (`circuits/lib/src/compliance.nr::run`'s `state_out`), so the minted
        // note's own recorded seq is one past the `ComplianceWitness.seq`/
        // `tx.seq` this transaction is anchored at.
        seq: Seq(seq.0 + 1),
        salt: new_salt,
        flags,
        state: next_state,
        facts,
    };
    let compliance_commitment_out = new_note.commitment(world.tag).expect("canonical");

    // This benchmark never ships a real `encryptedNotes` payload, but
    // `payload_commitment` still has to be derived from whatever payload would
    // ship, not the reverse, so an empty payload's commitment goes here.
    let payload_commitment = Payload::default().commitment();

    let public = deposit::Fields {
        commitment,
        token: Bytes32::from(tx.token),
        amount,
        attestation_root,
        velocity_nullifier,
        compliance_commitment_out,
        epoch,
        epoch_seconds: shielded_pool_compliance::EPOCH_SECONDS,
        policy_source_hash: world.policy_source_hash,
        commitment_root: world.commitments.root().unwrap_or(Bytes32::from([0u8; 32])),
        attester_revocation_root: world.revocations.root(),
        min_accepted_generation: 1,
        payload_commitment,
    };
    require_canonical(&public.ordered()).expect("canonical public inputs");

    DepositWitness {
        public,
        spending_key: alice_sk,
        note_salt: output_note.salt,
        attestation: attestation_witness(&world, leaf, generation, issued_at, expires_at),
        compliance: base_compliance_witness(epoch, new_salt),
    }
}

fn build_transfer_witness() -> TransferWitness {
    let world = new_world();
    let alice_sk = SpendingKey::random();
    let alice = alice_sk.derive_owner_pubkey();
    let bob = SpendingKey::random().derive_owner_pubkey();
    let (generation, issued_at, expires_at) = (Generation(1), 0u64, u64::MAX);

    let alice_leaf = insert_attestation_leaf(
        &world.attestations,
        alice,
        world.attester,
        generation,
        issued_at,
        expires_at,
    );
    let bob_leaf = insert_attestation_leaf(
        &world.attestations,
        bob,
        world.attester,
        generation,
        issued_at,
        expires_at,
    );
    let attestation_root = world.attestations.root().expect("nonempty");

    let spent_note = Note::new(world.token, 10_000, alice);
    let spent_index = world
        .commitments
        .insert(spent_note.commitment().expect("canonical"))
        .expect("insert");
    let commitment_root = world.commitments.root().expect("nonempty");

    let epoch = world.epoch;
    let seq = Seq(0);
    let owner_out = [bob, alice];
    // The transfer circuit requires amount_in_0 + amount_in_1 == amount_out_0 +
    // amount_out_1 exactly: the spent note carries 10,000, so the two outputs must
    // sum to 10,000 too.
    let amount_out = [400u64, 10_000u64 - 400];
    let tx = tx_facts::transfer(epoch, seq, world.token, alice, owner_out, amount_out)
        .expect("canonical");
    let prev_state = ReferencePolicy::zero();
    let next_state = ReferencePolicy::advance(prev_state, &tx).expect("no overflow");
    let flags =
        ReferencePolicy::evaluate(&tx, prev_state, next_state).expect("never blocks");

    let output_notes = [
        Note::new(world.token, amount_out[0], owner_out[0]),
        Note::new(world.token, amount_out[1], owner_out[1]),
    ];
    let commitment_out = [
        output_notes[0].commitment().expect("canonical"),
        output_notes[1].commitment().expect("canonical"),
    ];
    let velocity_nullifier = VelocityNullifier::derive(&alice_sk, epoch, seq).0;
    let facts = Facts {
        counterparty: [
            Bytes32::from(tx.counterparty[0]),
            Bytes32::from(tx.counterparty[1]),
        ],
        amount_out,
        exit: Bytes32::from(tx.exit),
    };
    let new_salt = random_salt();
    let new_note = ComplianceNote::<ReferencePolicy> {
        owner_pubkey: alice,
        epoch,
        seq: Seq(seq.0 + 1),
        salt: new_salt,
        flags,
        state: next_state,
        facts,
    };
    let compliance_commitment_out = new_note.commitment(world.tag).expect("canonical");

    let nullifier_0 = spent_note.nullifier(&alice_sk).expect("canonical");
    let padding_note = Note::zero(world.token, alice);
    let nullifier_1 = padding_note.nullifier(&alice_sk).expect("canonical");

    // This benchmark never ships a real `encryptedNotes` payload, but
    // `payload_commitment` still has to be derived from whatever payload would
    // ship, not the reverse, so an empty payload's commitment goes here.
    let payload_commitment = Payload::default().commitment();

    let public = transfer::Fields {
        nullifier_0,
        nullifier_1,
        commitment_out_0: commitment_out[0],
        commitment_out_1: commitment_out[1],
        commitment_root,
        velocity_nullifier,
        compliance_commitment_out,
        epoch,
        epoch_seconds: shielded_pool_compliance::EPOCH_SECONDS,
        policy_source_hash: world.policy_source_hash,
        attestation_root,
        attester_revocation_root: world.revocations.root(),
        min_accepted_generation: 1,
        payload_commitment,
    };
    require_canonical(&public.ordered()).expect("canonical public inputs");

    let inputs = [
        InputNoteWitness {
            amount: spent_note.amount,
            salt: spent_note.salt,
            proof: world.commitments.get_proof(spent_index).expect("proof"),
        },
        InputNoteWitness {
            amount: 0,
            salt: padding_note.salt,
            proof: MerklePath::new(vec![]),
        },
    ];
    let outputs = [
        OutputNoteWitness {
            amount: output_notes[0].amount,
            owner: output_notes[0].owner_pubkey,
            salt: output_notes[0].salt,
        },
        OutputNoteWitness {
            amount: output_notes[1].amount,
            owner: output_notes[1].owner_pubkey,
            salt: output_notes[1].salt,
        },
    ];

    TransferWitness {
        public,
        spending_key: alice_sk,
        token: world.token,
        inputs,
        outputs,
        subject_attestation: attestation_witness(
            &world, alice_leaf, generation, issued_at, expires_at,
        ),
        output_attestations: [
            attestation_witness(&world, bob_leaf, generation, issued_at, expires_at),
            attestation_witness(&world, alice_leaf, generation, issued_at, expires_at),
        ],
        compliance: base_compliance_witness(epoch, new_salt),
    }
}

